import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join, dirname, basename } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';

/** Load a team's local configuration, creating it only for init/start.
 * The project ID separates repositories. The bearer token authenticates local
 * RPC, and is unrelated to Claude/OpenAI model credentials. Neither is logged.
 * Keep the configuration beside SQLite so a Docker volume preserves both.
 */
export function loadConfig(project = process.cwd(), { create = false } = {}) {
  const root = resolve(project);
  const directory = join(root, '.agentmesh');
  const file = join(directory, 'config.json');
  if (create) {
    mkdirSync(join(directory, 'state'), { recursive: true, mode: 0o700 });
    const config = {
      version: 1, projectId: randomUUID(), name: process.env.AGENTMESH_PROJECT_NAME || basename(root),
      url: 'http://127.0.0.1:4317', token: randomBytes(32).toString('hex'),
      heartbeatMs: 15000, offlineMs: 60000,
    };
    // Exclusive creation avoids replacing an existing team's ID or token on
    // restart. EEXIST means reuse it, not generate a different project.
    try { writeFileSync(file, JSON.stringify(config, null, 2) + '\n', { flag: 'wx', mode: 0o600 }); }
    catch (error) { if (error.code !== 'EEXIST') throw error; }
  }
  let config;
  try { config = JSON.parse(readFileSync(file, 'utf8')); }
  catch (error) {
    if (error.code === 'ENOENT') throw new Error(`No Agent Mesh project at ${root}. Run agentmesh init first.`);
    throw error;
  }
  if (config.version !== 1 || !config.projectId || !config.name || typeof config.token !== 'string' || config.token.length < 32 ||
      !Number.isInteger(config.heartbeatMs) || config.heartbeatMs < 100 ||
      !Number.isInteger(config.offlineMs) || config.offlineMs < config.heartbeatMs * 2) {
    throw new Error('Invalid Agent Mesh configuration.');
  }
  const url = new URL(config.url);
  // The HTTP transport intentionally has no remote/TLS mode at this milestone.
  // Inside Docker, bridges also use loopback in the broker container.
  if (url.protocol !== 'http:' || !['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname)) {
    throw new Error('The broker URL must use local HTTP.');
  }
  return { ...config, root, directory, database: join(directory, 'state', 'mesh.db') };
}

export function loadIdentity(config, name) {
  // A name doubles as a filename, so disallow path separators and traversal.
  // Persist only the identity secret here; a new session UUID is generated by
  // AgentClient on each launch and is never treated as a durable identity.
  if (!/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$/.test(name)) throw new Error('Agent names must use 1–64 letters, digits, underscores or hyphens.');
  const file = join(config.directory, 'identities', `${name}.json`);
  mkdirSync(dirname(file), { recursive: true, mode: 0o700 });
  try {
    writeFileSync(file, JSON.stringify({ name, secret: randomBytes(32).toString('hex') }), { flag: 'wx', mode: 0o600 });
  } catch (error) { if (error.code !== 'EEXIST') throw error; }
  return JSON.parse(readFileSync(file, 'utf8'));
}
