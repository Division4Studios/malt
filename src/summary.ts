/**
 * Generate a project-local README from committed broker state. The SQLite
 * database remains authoritative; this file is a secret-free navigation aid.
 *
 * @file
 */

import { randomUUID } from 'node:crypto';
import { readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { z } from 'zod/v3';

import { parseConnection } from './connector.ts';
import { selectAll, selectCount, selectOne } from './database.ts';
import { hasErrorCode } from './errors.ts';
import { objectiveQueueSchema } from './factory/objective-queue-schema.ts';

import type { MeshConfig } from './config.ts';
import type { DatabaseSync } from 'node:sqlite';

/**
 * Format the current time without relying on unavailable Temporal APIs.
 *
 * @returns UTC timestamp for durable records.
 */
export function timestamp(): string {
  const now = new Date();
  return now.toISOString();
}

/** One public agent entry in the generated project overview. */
export interface SummaryAgent {
  /** Agent name, excluding its credentials. */
  readonly name: string;
  /** Assigned team responsibility. */
  readonly role: string;
  /** Current presence. */
  readonly status: string;
}

/** Committed counts and roster, never message bodies or credentials. */
export interface SummaryState {
  /** Secret-free factory progress, when its ledger exists. */
  readonly factory?: readonly string[];
  /** Visible roster. */
  readonly agents: readonly SummaryAgent[];
  /** Unacknowledged messages. */
  readonly unreadMessages: number;
  /** Workers requesting a decision. */
  readonly pendingCheckIns: number;
  /** Last committed event sequence. */
  readonly revision: number;
  /** Orchestrator's public identity, when designated. */
  readonly lead: string | null;
}

/**
 * Replace a derived file atomically, leaving the previous copy intact on failure.
 *
 * @param file - File inside this project's state directory.
 * @param contents - Complete replacement content.
 * @throws {Error} For filesystem failures.
 */
export function writeAtomic(file: string, contents: string): void {
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- A sibling temporary file under the project state directory.
    writeFileSync(temporary, contents, { mode: 0o600, flag: 'wx' });
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- Atomic replacement of a project-derived file, never a database.
    renameSync(temporary, file);
  } finally {
    rmSync(temporary, { force: true });
  }
}

/**
 * Make a display value safe in a Markdown table.
 *
 * @param value - Public project or agent label.
 * @returns A single Markdown table cell.
 */
function cell(value: string): string {
  return value.replaceAll('|', String.raw`\|`).replaceAll(/[\n\r]/gv, ' ');
}

/**
 * Refresh README only when the committed state or directory inventory changes.
 *
 * @param config - Project-local paths and public name.
 * @param state - Committed roster and counters.
 * @throws {Error} For filesystem failures; callers must not undo committed work.
 */
export function refreshReadme(config: MeshConfig, state: SummaryState): void {
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- Inventory names only, within this project's state directory.
  const entries = readdirSync(config.directory, { withFileTypes: true })
    .filter((entry) => !entry.name.endsWith('.tmp'))
    .map((entry) => `- \`${cell(entry.name)}${entry.isDirectory() ? '/' : ''}\``)
    .toSorted((left, right) => left.localeCompare(right));
  const file = path.join(config.directory, 'README.md');
  const contents = [
    `# MALT state: ${cell(config.name)}`,
    '',
    'Generated by MALT from committed state. SQLite is authoritative. This file contains no credentials or conversation bodies.',
    '',
    `Workspace: ${cell(config.workspace ?? config.root)}`,
    `Event revision: ${String(state.revision)}`,
    `Team lead: ${state.lead ?? 'not designated'}`,
    `Unread messages: ${String(state.unreadMessages)}`,
    `Pending work requests: ${String(state.pendingCheckIns)}`,
    ...integrationOverview(config),
    ...(state.factory ?? []),
    '',
    '| Agent | Role | Presence |',
    '| --- | --- | --- |',
    ...state.agents.map((agent) => `| ${cell(agent.name)} | ${cell(agent.role)} | ${cell(agent.status)} |`),
    '',
    '## Files',
    '',
    ...entries,
    '',
    "`state/mesh.db` holds agents, conversations, broker messages, acknowledgements, assignments and event history. `identities/` and `config.json` contain local credentials. `github/` holds this workspace's GitHub connection, board snapshot and operation journal. `teams/` contains routing references; other projects keep their state in their own `.malt` folders.",
    '',
    'Runtime files are ignored by Git. Back up the entire `.malt` directory after stopping the broker cleanly. Put human-maintained project notes in a separate file; this README is regenerated.',
    '',
  ].join('\n');
  let previous = '';
  try {
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- Read the derived README only.
    previous = readFileSync(file, 'utf8');
  } catch (error) {
    if (!hasErrorCode(error, 'ENOENT')) {
      throw error;
    }
  }
  if (previous !== contents) {
    writeAtomic(file, contents);
  }
}

/**
 * Count durable learning artifacts without reading their potentially large bodies.
 *
 * @param directory - Project-local evidence directory.
 * @returns Number of JSON evidence records.
 * @throws {Error} For filesystem failures other than a missing category.
 */
function artifactCount(directory: string): number {
  try {
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- Count only project-local artifact names.
    return readdirSync(directory).filter((entry) => entry.endsWith('.json')).length;
  } catch (error) {
    if (!hasErrorCode(error, 'ENOENT')) {
      throw error;
    }
    return 0;
  }
}

/**
 * Read an integration JSON document without a runtime configuration dependency.
 *
 * @param file - Project-local integration file.
 * @returns Unvalidated document, checked by the caller's schema.
 */
function readIntegrationFile(file: string): unknown {
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- Only project-local overview inputs are read.
  return JSON.parse(readFileSync(file, 'utf8'));
}

/**
 * Summarize saved GitHub and learning state without including credentials.
 *
 * @param config - Current project's paths.
 * @returns Public integration details for the generated README.
 */
function integrationOverview(config: MeshConfig): string[] {
  const lines = [
    `Learning: ${String(artifactCount(path.join(config.directory, 'knowledge', 'lessons')))} lessons, ${String(artifactCount(path.join(config.directory, 'knowledge', 'sources')))} pinned sources, ${String(artifactCount(path.join(config.directory, 'knowledge', 'candidates')))} skill candidates.`,
  ];
  try {
    const { legacy: connection } = parseConnection(
      readIntegrationFile(path.join(config.directory, 'github', 'connection.json')),
    );
    lines.push(`GitHub repository: ${cell(connection.repository)}`, `GitHub Project: ${connection.project.url}`);
  } catch {
    lines.push('GitHub Project: not connected or saved connection needs repair.');
  }
  try {
    const skills = z
      .array(z.object({ name: z.string(), state: z.enum(['active', 'archived']) }))
      .parse(readIntegrationFile(path.join(config.directory, 'skills', 'manifest.json')));
    const active = skills
      .filter((skill) => skill.state === 'active')
      .map((skill) => cell(skill.name))
      .join(', ');
    lines.push(`Active project skill overrides: ${active === '' ? 'none' : active}`);
  } catch (error) {
    lines.push(
      hasErrorCode(error, 'ENOENT')
        ? 'Active project skill overrides: none; bundled stage guidance remains available.'
        : 'Active project skill overrides: saved manifest needs repair; inspect skills/manifest.json.',
    );
  }
  return lines;
}

/**
 * Collect secret-free committed state for the project README.
 *
 * @param database - Project SQLite connection after commit.
 * @param lead - Public orchestrator identity.
 * @returns Counts and visible roster.
 */
export function summarize(database: DatabaseSync, lead: string | null): SummaryState {
  const agents = selectAll(
    database,
    z.object({ name: z.string(), role: z.string(), status: z.string() }),
    "SELECT name, role, status FROM agents WHERE lifetime != 'ended' ORDER BY name",
  );
  return {
    factory: factoryOverview(database),
    agents,
    lead,
    revision: selectCount(database, 'SELECT COALESCE(MAX(seq), 0) AS count FROM events'),
    unreadMessages: selectCount(
      database,
      "SELECT COUNT(*) AS count FROM messages m JOIN agents a ON a.id = m.recipient WHERE m.acknowledged_at IS NULL AND a.lifetime != 'ended'",
    ),
    pendingCheckIns: selectCount(
      database,
      "SELECT COUNT(*) AS count FROM worker_coordination WHERE phase = 'AWAITING_LEAD'",
    ),
  };
}

/**
 * Summarize only public factory counts after a committed transaction.
 *
 * @param database - Project ledger.
 * @returns Factory navigation and lifecycle counts.
 */
function factoryOverview(database: DatabaseSync): string[] {
  const exists = selectCount(
    database,
    "SELECT COUNT(*) AS count FROM sqlite_master WHERE type='table' AND name='factory_settings'",
  );
  if (exists === 0) {
    return [];
  }
  const phases = selectAll(
    database,
    z.object({ phase: z.string(), count: z.number() }),
    'SELECT phase, COUNT(*) AS count FROM factory_tasks GROUP BY phase',
  );
  const live = selectCount(database, "SELECT COUNT(*) AS count FROM factory_jobs WHERE state='running'");
  const requests = selectCount(
    database,
    "SELECT COUNT(*) AS count FROM factory_features WHERE json_extract(data,'$.phase') != 'done' AND json_extract(data,'$.scopeCleanup') IS NULL",
  );
  const deliveries = phases.map((phase) => `${phase.phase} ${String(phase.count)}`).join(', ');
  const description = deliveries === '' ? 'none' : deliveries;
  return [
    `Factory: ${String(live)} live bounded jobs, ${String(requests)} pending product objectives.`,
    `Deliveries: ${description}.`,
    ...objectiveQueueOverview(database),
    'Factory policy, attempts, handoffs and check logs: `factory/`. Owned branches and snapshots: `worktrees/`. Bundled role skills and pinned provenance: `skills/builtin/`.',
    'Human-authorized reusable learning handoffs and source objective receipts: `factory/maintenance/`.',
  ];
}

/**
 * Describe saved dispatch controls only after the additive queue table exists.
 *
 * @param database - Selected project's committed ledger.
 * @returns Public priority status, without operator message bodies.
 */
function objectiveQueueOverview(database: DatabaseSync): string[] {
  const exists = selectCount(
    database,
    "SELECT COUNT(*) AS count FROM sqlite_master WHERE type='table' AND name='factory_objective_queue'",
  );
  if (exists === 0) {
    return [];
  }
  const row = selectOne(
    database,
    z.object({ data: z.string() }),
    'SELECT data FROM factory_objective_queue WHERE id=1',
  );
  if (row === undefined) {
    return [];
  }
  const queue = objectiveQueueSchema.parse(JSON.parse(row.data));
  const hasRanks =
    selectCount(
      database,
      "SELECT COUNT(*) AS count FROM sqlite_master WHERE type='table' AND name='factory_objective_order'",
    ) > 0;
  const revision = hasRanks
    ? (selectOne(
        database,
        z.object({ revision: z.number() }),
        'SELECT revision FROM factory_objective_order WHERE id=1',
      )?.revision ?? queue.revision)
    : queue.revision;
  const positions = selectCount(
    database,
    "SELECT COUNT(*) AS count FROM factory_features WHERE json_extract(data,'$.phase') != 'done' AND json_extract(data,'$.scopeReplacement') IS NULL",
  );
  return [
    `Objective priority: revision ${String(revision)}, ${String(positions)} unfinished positions; requested focus ${queue.focusedFeatureId ?? 'all objectives'}. Completed or superseded focus releases automatically.`,
  ];
}
